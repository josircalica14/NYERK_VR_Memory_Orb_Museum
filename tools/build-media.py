"""
build-media.py
---------------
Regenerates the two derived media artifacts used by the UI shell:

  1. js/media-manifest.js  - every real file per member card, so the directory
                             and memory viewer never request a missing asset.
  2. assets/thumbs/**      - 320px previews (plus one avatar per member) so
                             panels show real photos instead of downloading
                             14 MB originals as thumbnails.

Usage (from the project root):
    python tools/build-media.py

Requires Pillow. Safe to re-run; it only rewrites files it owns.
"""

import json
import os
import re
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: pip install Pillow")

ROOT = "assets/portfolios"
IMAGES = "assets/images"
THUMBS = "assets/thumbs"
ORBS = "assets/orbs"
MANIFEST = "js/media-manifest.js"
IMAGE_EXT = re.compile(r"\.(jpe?g|png|webp)$", re.I)
MEDIA_EXT = re.compile(r"\.(jpe?g|png|webp|mp4|webm)$", re.I)
THUMB_MAX = 320
THUMB_QUALITY = 70
# Orb faces are 512px canvas textures, so this tier is 1:1 with them: no
# upscaling on screen, and still a fraction of a multi-megabyte original.
ORB_MAX = 512
ORB_QUALITY = 82


def sort_key(name):
    match = re.match(r"(\d+)", name)
    return (0, int(match.group(1))) if match else (1, name)


def build_manifest():
    out = {}
    for folder in sorted(os.listdir(ROOT)):
        folder_dir = os.path.join(ROOT, folder)
        if not os.path.isdir(folder_dir):
            continue
        cards = {}
        for card in sorted(os.listdir(folder_dir)):
            card_dir = os.path.join(folder_dir, card)
            if not os.path.isdir(card_dir):
                continue
            files = sorted(
                (f for f in os.listdir(card_dir) if MEDIA_EXT.search(f)),
                key=sort_key,
            )
            if files:
                cards[card] = files
        out[folder] = cards

    body = (
        "/* Generated by tools/build-media.py from assets/portfolios.\n"
        " * Real media per member card, so the UI shell never probes missing files.\n"
        " * Do not edit by hand - re-run the script after adding or moving media. */\n"
        "window.portfolioMedia = "
        + json.dumps(out, indent=2, ensure_ascii=False)
        + ";\n"
    )
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    with open(MANIFEST, "w", encoding="utf-8") as handle:
        handle.write(body)

    cards = sum(len(v) for v in out.values())
    files = sum(len(f) for v in out.values() for f in v.values())
    print(f"manifest: {len(out)} members, {cards} cards, {files} files")


def make_thumb(src, dest, max_side=THUMB_MAX):
    if os.path.exists(dest) and os.path.getmtime(dest) >= os.path.getmtime(src):
        return False
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with Image.open(src) as img:
        img = img.convert("RGB")
        img.thumbnail((max_side, max_side))
        img.save(dest, "JPEG", quality=THUMB_QUALITY, optimize=True, progressive=True)
    return True


def build_thumbs():
    written = 0
    for folder in sorted(os.listdir(ROOT)):
        folder_dir = os.path.join(ROOT, folder)
        if not os.path.isdir(folder_dir):
            continue
        for card in sorted(os.listdir(folder_dir)):
            card_dir = os.path.join(folder_dir, card)
            if not os.path.isdir(card_dir):
                continue
            for name in sorted(os.listdir(card_dir), key=sort_key):
                if not IMAGE_EXT.search(name):
                    continue
                src = os.path.join(card_dir, name)
                dest = os.path.join(THUMBS, folder, card, os.path.splitext(name)[0] + ".jpg")
                try:
                    if make_thumb(src, dest):
                        written += 1
                except Exception as err:  # keep going; one bad file must not stop the build
                    print(f"  skip {src}: {err}")

    # One avatar per member, cropped square from the bubble portrait.
    # The portrait filename does not always match the folder name, so read the
    # mapping from config.js (image: "..." precedes folder: "..." in each item).
    portraits = {}
    try:
        with open("js/config.js", encoding="utf-8") as handle:
            config = handle.read()
        for image, folder in re.findall(r'image:\s*"([^"]+)"[\s\S]*?folder:\s*"([^"]+)"', config):
            portraits[folder] = image
    except OSError as err:
        print(f"  config.js unreadable ({err}); falling back to folder names")

    for folder in sorted(os.listdir(ROOT)):
        src = portraits.get(folder)
        if not src:
            for ext in ("jpg", "JPG", "png"):
                candidate = os.path.join(IMAGES, f"{folder}.{ext}")
                if os.path.exists(candidate):
                    src = candidate
                    break
        if src and os.path.exists(src):
            dest = os.path.join(THUMBS, folder, "_avatar.jpg")
            try:
                if make_thumb(src, dest, max_side=192):
                    written += 1
            except Exception as err:
                print(f"  skip avatar {src}: {err}")
        else:
            print(f"  no portrait for {folder}")

    print(f"thumbs: {written} written")


def build_orb_faces():
    written = 0
    for folder in sorted(os.listdir(ROOT)):
        folder_dir = os.path.join(ROOT, folder)
        if not os.path.isdir(folder_dir):
            continue
        for card in sorted(os.listdir(folder_dir)):
            card_dir = os.path.join(folder_dir, card)
            if not os.path.isdir(card_dir):
                continue
            for name in sorted(os.listdir(card_dir), key=sort_key):
                if not IMAGE_EXT.search(name):
                    continue
                src = os.path.join(card_dir, name)
                dest = os.path.join(ORBS, folder, card, os.path.splitext(name)[0] + ".jpg")
                try:
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    if os.path.exists(dest) and os.path.getmtime(dest) >= os.path.getmtime(src):
                        continue
                    with Image.open(src) as img:
                        img = img.convert("RGB")
                        img.thumbnail((ORB_MAX, ORB_MAX))
                        img.save(dest, "JPEG", quality=ORB_QUALITY, optimize=True, progressive=True)
                    written += 1
                except Exception as err:
                    print(f"  skip orb {src}: {err}")

    print(f"orb faces: {written} written")


if __name__ == "__main__":
    build_manifest()
    build_thumbs()
    build_orb_faces()
